export function getGalleryItemBySlug(slug: string): GalleryItem | undefined {
  return GALLERY_ITEMS.find((item) => item.slug === slug);
}

export function getGalleryItemsByCategorySlug(categorySlug: string): GalleryItem[] {
  const exact = GALLERY_ITEMS.filter((item) => item.categorySlug === categorySlug);
  if (exact.length >= 3) return exact;
  // Supplement thoughtfully with closely related stories so every category page feels rich
  const others = GALLERY_ITEMS.filter((item) => item.categorySlug !== categorySlug).slice(0, 4 - exact.length);
  return [...exact, ...others];
}
